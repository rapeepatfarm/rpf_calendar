-- วันที่วางแผนไว้ "ครั้งแรก" ก่อนถูกเลื่อนตามวันที่กดเริ่มจริง
--
-- ต้องเก็บไว้เพราะตั้งแต่นี้ไป planned_date จะขยับตามความจริง
-- ถ้าไม่เก็บของเดิม จะไม่มีทางรู้อีกเลยว่าเดิมวางแผนไว้วันไหน แปลว่า
--   · ตอบไม่ได้ว่างานนี้เลื่อนจากแผนไปกี่วัน
--   · "% ทำตรงแผน" จะกลายเป็น 100% ตลอดกาล เพราะแผนถูกขยับไปทับความจริงแล้ว
--     (reports.py จึงตัดสินตรงแผน/ช้า จากคอลัมน์ _original ถ้ามี)
--
-- เขียนครั้งเดียวตอนถูกเลื่อนครั้งแรกเท่านั้น กดเริ่ม-ถอน-เริ่มใหม่หลายรอบ
-- ค่านี้ต้องไม่เปลี่ยน ไม่งั้น "แผนเดิม" จะกลายเป็นแผนที่เพิ่งเลื่อนไปเมื่อกี้
ALTER TABLE activities ADD COLUMN IF NOT EXISTS planned_date_original DATE;
ALTER TABLE activities ADD COLUMN IF NOT EXISTS planned_end_date_original DATE;

