-- บังคับเปลี่ยนรหัสผ่านตอนล็อกอินครั้งถัดไป
-- รันด้วย: psql -U postgres -d rpf_calendar -f migrations\005_force_password_change.sql
-- =============================================================

-- ตั้งเป็น TRUE เมื่อผู้ดูแลระบบตั้งรหัสให้ (สร้างบัญชีใหม่ / ตั้งรหัสใหม่ให้)
-- ผู้ใช้จะเข้าหน้าอื่นไม่ได้จนกว่าจะตั้งรหัสของตัวเอง
ALTER TABLE users ADD COLUMN IF NOT EXISTS must_change_password BOOLEAN NOT NULL DEFAULT FALSE;

-- ── ครั้งเดียว: บังคับทุกบัญชีที่มีอยู่ก่อนเปิดให้เข้าจากอินเทอร์เน็ต ──
-- รหัสที่ตั้งกันไว้ตอนใช้แค่ในวง LAN อาจสั้นหรือเดาง่าย ซึ่งไม่พอเมื่อหน้าล็อกอิน
-- ออกไปอยู่บนอินเทอร์เน็ต · ทำใน migration แทนสคริปต์แยก เพื่อให้รันซ้ำแล้วไม่พัง
-- และมีร่องรอยว่าบังคับตอนไหน
UPDATE users SET must_change_password = TRUE WHERE active;

-- ── หมายเหตุ ─────────────────────────────────────────────────
-- การบังคับนี้ทำงานใน auth.require_login() — ถ้าธงเป็น TRUE จะเด้งไปหน้า
-- บัญชีของฉันทุกครั้งที่เปิดหน้าอื่น · ยกเว้นหน้าบัญชีของฉันเองกับการออกจากระบบ
-- ไม่งั้นผู้ใช้จะติดอยู่ในวงวนไม่มีทางออก
