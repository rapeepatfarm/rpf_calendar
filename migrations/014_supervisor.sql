-- ผู้ใช้สั่งว่าช่อง "ผู้รับผิดชอบ" ให้เลือกได้เฉพาะตำแหน่งหัวหน้างานขึ้นไป
--
-- ทำไมเป็นคอลัมน์ ไม่ใช่ดูจากข้อความในช่อง position:
--   position เป็นข้อความอิสระ ("หัวหน้าโรงผสมอาหาร" / "หัวหน้าบ่อ BIOGAS" / "สัตวบาล")
--   ถ้าไปจับคำว่า "หัวหน้า" ในโค้ด พอมีคนพิมพ์ "หน.เล้า A" หรือ "ผจก.ฟาร์ม"
--   เขาจะหายจากรายการเงียบๆ โดยไม่มีอะไรเตือน — บทเรียนเดียวกับ needs_start (010)
--
-- ทำไมไม่ดูจาก users.role:
--   หัวหน้าบางคนอาจไม่มีบัญชีล็อกอิน (ไม่ได้ใช้มือถือ) แต่ยังต้องเป็นผู้รับผิดชอบงานได้
--   ทะเบียนพนักงานจึงต้องตอบเรื่องนี้ได้ด้วยตัวเอง ไม่ผูกกับการมีบัญชี
ALTER TABLE staff ADD COLUMN IF NOT EXISTS is_supervisor BOOLEAN NOT NULL DEFAULT FALSE;

-- ตั้งค่าตั้งต้นจากคนที่ผูกบัญชีระดับหัวหน้างานขึ้นไปไว้แล้ว — ตรงกับความจริงของฟาร์มนี้
-- (หมอภพ/หมอแป้ง/หมอฟิล์ม/Tee/Dee เป็น manager อยู่แล้ว ส่วนคนงานรายวันไม่มีบัญชี)
-- คนที่เหลือผู้ใช้ติ๊กเพิ่มเองได้จากหน้าจัดการพนักงาน
UPDATE staff s SET is_supervisor = TRUE
  FROM users u
 WHERE u.id = s.user_id AND u.role IN ('admin', 'manager');

CREATE INDEX IF NOT EXISTS staff_supervisor_idx ON staff (is_supervisor) WHERE active;

