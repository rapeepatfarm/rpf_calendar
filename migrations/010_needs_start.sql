-- รันด้วย: psql -U postgres -d rpf_calendar -f migrations\010_needs_start.sql
-- =============================================================

-- ค่าตั้งต้นรายประเภท — ฟอร์มเพิ่มกิจกรรมติ๊กหรือไม่ติ๊กให้ตามประเภทที่เลือก
--
-- เก็บเป็นคอลัมน์ในทะเบียนประเภท **ไม่ใช่ฝังชื่อประเภทไว้ในโค้ด**
-- ถ้าฝังชื่อ ("พนักงานลาหยุด" / "แจ้งให้ทราบ") ไว้ พอผู้ใช้เปลี่ยนชื่อประเภท
-- หรือเพิ่มประเภทแจ้งเตือนใหม่ ค่าตั้งต้นจะเงียบหายไปโดยไม่มีอะไรเตือน
-- แบบนี้ผู้ใช้ตั้งเองได้จากหน้าทะเบียนประเภทกิจกรรม
ALTER TABLE activity_categories
    ADD COLUMN IF NOT EXISTS needs_start BOOLEAN NOT NULL DEFAULT TRUE;

-- ค่าจริงของกิจกรรมแต่ละรายการ — คนกรอกเปลี่ยนได้เสมอ ไม่ผูกกับประเภทตายตัว
-- (ประเภทเป็นแค่ "ค่าตั้งต้น" ตอนกรอก ไม่ใช่กฎบังคับ)
ALTER TABLE activities
    ADD COLUMN IF NOT EXISTS needs_start BOOLEAN NOT NULL DEFAULT TRUE;

-- สองประเภทที่ผู้ใช้ระบุมา
UPDATE activity_categories SET needs_start = FALSE
 WHERE name IN ('พนักงานลาหยุด', 'แจ้งให้ทราบ');

-- กิจกรรมที่มีอยู่แล้วของสองประเภทนั้น และยังไม่มีใครกดเริ่ม ให้ตามค่าใหม่ด้วย
-- กันเฉพาะที่ยังไม่ถูกแตะ — ถ้ามีคนกดเริ่มไปแล้วแปลว่ามันเป็นงานที่ต้องทำจริง
UPDATE activities a SET needs_start = FALSE
  FROM activity_categories c
 WHERE a.category_id = c.id AND NOT c.needs_start
   AND a.started_at IS NULL AND a.status = 'planned';

-- ── ความหมายของ needs_start = FALSE ─────────────────────────
--   · ไม่มีปุ่ม "เริ่มงาน" และ services/activities.start() ปฏิเสธที่เซิร์ฟเวอร์ด้วย
--   · ไม่นับเป็นงานค้าง · days_late เป็น 0 เสมอ
--   · ตัวปิดอัตโนมัติ (close_stale) ข้ามไป
--   · ยังขึ้นบนปฏิทินและในลิสต์งานต่อไปตามปกติ เพราะเป็นข้อมูลที่คนต้องเห็น
--
-- ที่ต้องกันงานพวกนี้ออกจาก "งานค้าง" เพราะมันจะไม่มีวันถูกกดเริ่ม
-- ถ้าไม่กัน มันจะกองสะสมในหน้างานค้างตลอดไปจนบังงานจริงที่ต้องทำ
