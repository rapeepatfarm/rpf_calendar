-- TRUE = คนที่นี่แก้วันเอง · รอบซิงค์ถัดไปห้ามเขียนทับวันนี้
-- ฟิลด์อื่น (ชื่องาน หมายเหตุ ความสำคัญ) ยังให้ต้นทางเป็นเจ้าของเหมือนเดิม
ALTER TABLE activities ADD COLUMN IF NOT EXISTS date_overridden BOOLEAN NOT NULL DEFAULT FALSE;

-- ฝั่ง RPF Farm ดึงวันที่แก้แล้วกลับไปใช้ผ่าน services/calendar_pull.py
-- จึงต้องหาแถวที่ถูกแก้ให้เร็ว โดยไม่สแกนทั้งตาราง
CREATE INDEX IF NOT EXISTS activities_overridden_idx
    ON activities (source_system, external_id)
 WHERE date_overridden AND source_system IS NOT NULL;

-- ── หลักการที่ต้องรักษาไว้ ───────────────────────────────────
-- ทิศทางข้อมูลยังเป็น "ต่างฝ่ายต่างดึง ไม่มีใครเขียนข้าม DB" เหมือนเดิม
--     แผนกิจกรรม  ฟาร์ม → ปฏิทิน   (ปฏิทินดึง)
--     ผลที่ทำจริง ปฏิทิน → ฟาร์ม   (ฟาร์มดึง)
--     วันที่แก้ใหม่ ปฏิทิน → ฟาร์ม   (ฟาร์มดึง — ช่องทางเดียวกับผลที่ทำจริง)
--
-- ปฏิทิน "ไม่" เขียนลง DB ของฟาร์ม · ฟาร์มเป็นฝ่ายมาอ่านเอง
-- ทำแบบนี้เพื่อให้บัญชี rpf_readonly ยังเป็น SELECT อย่างเดียวได้ตามเดิม
