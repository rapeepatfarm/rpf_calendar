-- แถวนี้ถูกดันออกไปเพราะ "งานตัวไหน" ถูกเลื่อนมาทับวันของมัน
--
-- ต้องมีเพราะการดันรอบถัดไป (migration 008 + apply_shift) เป็นการที่ระบบ
-- ไปขยับแถวที่ผู้ใช้ไม่ได้แตะ · ถ้าไม่รู้ว่าใครเป็นคนสั่งให้ขยับ ก็ย้อนกลับไม่ได้
-- แล้วการกดถอนการเริ่มงานจะคืนได้แค่ครึ่งเดียว — ตรรกะจะไม่เหมือนกันทั้งโปรแกรม
--
-- คู่กับ planned_date_original ที่มีอยู่แล้ว: คอลัมน์นั้นบอก "วันเดิมคือวันไหน"
-- คอลัมน์นี้บอก "ใครเป็นคนทำให้ต้องย้าย" · มีครบสองอย่างจึงย้อนกลับได้
--
-- ON DELETE SET NULL เพราะรอบอนาคตที่ยังไม่ได้เริ่มถูกลบจริงได้
-- (routers/plans.py ลบทิ้งแล้วสร้างใหม่ตอนแก้แผนงานประจำ)
ALTER TABLE activities
    ADD COLUMN IF NOT EXISTS shift_source_id BIGINT
        REFERENCES activities(id) ON DELETE SET NULL;

-- ตอนถอนการเริ่มงานต้องหา "รอบที่ถูกดันเพราะงานนี้" ให้เร็ว โดยไม่สแกนทั้งตาราง
CREATE INDEX IF NOT EXISTS activities_shift_source_idx
    ON activities (shift_source_id) WHERE shift_source_id IS NOT NULL;

-- ── ลำดับการคืนวันที่ต้องรักษาไว้ ────────────────────────────
-- คืนจาก "ต้นลูกโซ่ไปหาปลาย" คือเรียงตาม planned_date_original จากน้อยไปมาก
-- เพราะปลายทางของแต่ละตัวจะถูกปล่อยว่างโดยตัวก่อนหน้าพอดี
--     A กลับไปวันเดิมของ A  ->  ปล่อยวันนี้ว่าง
--     B กลับไปวันนี้         ->  ปล่อยวันที่ B ไปอยู่ว่าง
--     C กลับไปวันที่ B เคยอยู่
-- ถ้าคืนสลับลำดับ จะไปชน UNIQUE (series_id, planned_date) แล้วพังกลางคัน
