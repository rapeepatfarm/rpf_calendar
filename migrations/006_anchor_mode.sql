-- รันด้วย: psql -U postgres -d rpf_calendar -f migrations\006_anchor_mode.sql
-- =============================================================

-- fixed      = ยึดวันตายตัวตามปฏิทิน (พฤติกรรมเดิม)
--              เช่น ทุกวันที่ 15 ของทุก 3 เดือน -> 15 ต.ค. · 15 ม.ค. · 15 เม.ย.
--              งานจะเสร็จช้าหรือเร็วไม่มีผลกับรอบถัดไป
--
-- after_done = นับรอบถัดไปจากวันที่กดเสร็จจริง + ระยะเวลาที่ตั้งไว้
--              เช่น แผน 15 ต.ค. ทุก 3 เดือน แต่ทำเสร็จจริง 30 ต.ค.
--              -> รอบถัดไปเป็น 30 ม.ค. (ไม่ใช่ 15 ม.ค.)
--              ใช้กับงานที่ "ต้องเว้นระยะห่างจริง" เช่น ล้างถัง พ่นยา เปลี่ยนไส้กรอง
ALTER TABLE activity_series ADD COLUMN IF NOT EXISTS anchor_mode TEXT NOT NULL DEFAULT 'fixed';

ALTER TABLE activity_series DROP CONSTRAINT IF EXISTS series_anchor_mode_chk;
ALTER TABLE activity_series ADD CONSTRAINT series_anchor_mode_chk
    CHECK (anchor_mode IN ('fixed', 'after_done'));

-- ── หมายเหตุสำคัญ ────────────────────────────────────────────
-- โหมด after_done สร้างกิจกรรมล่วงหน้าได้ **ครั้งละ 1 รอบเท่านั้น**
-- เพราะวันของรอบถัดไปขึ้นกับว่ารอบปัจจุบันจะเสร็จเมื่อไร ซึ่งยังไม่รู้
-- (ต่างจาก fixed ที่คำนวณล่วงหน้า 12 เดือนได้เลย)
--
-- รอบใหม่ถูกสร้างตอนปิดงานรอบเดิม — ดู scheduler.ensure_next_occurrence()
-- ปิดแบบ done  -> นับจากวันที่ทำเสร็จ
-- ปิดแบบ missed/cancelled -> นับจากวันสุดท้ายที่วางแผนไว้ (เพราะไม่ได้ลงมือทำ)
