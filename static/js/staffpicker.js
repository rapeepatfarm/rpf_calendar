/* staffpicker.js — ตัวช่วยเลือกพนักงานที่ใช้ร่วมกันในฟอร์มหน้าที่ประจำและฟอร์มวันลา

   ทำสองอย่าง:
     1. กรองตามฝ่าย — ฟาร์มมีพนักงานหลายสิบคน ลิสต์เดียวหายาก
     2. ซ่อนคนที่ "ถูกเลือกไปแล้ว" — คนที่ประจำจุดนั้นอยู่แล้ว / คนที่มีวันลาคาบช่วงที่กรอก
        จะได้ไม่เลือกซ้ำในครั้งถัดไป แล้วไปเจอ error ตอนกดบันทึก

   **ซ่อนบนหน้าจอเท่านั้น** การกันจริงยังอยู่ที่เซิร์ฟเวอร์ (staffing.validate*) เสมอ
   เพราะยิง POST ตรงได้ และข้อมูลอาจเปลี่ยนไปแล้วระหว่างที่เปิดฟอร์มค้างไว้

   ตัวเลือกถูก **ตัดออกจาก DOM จริง** ด้วย x-for ไม่ใช่ x-show บน <option>
   เพราะบางเบราว์เซอร์ไม่ซ่อน option ที่ display:none ให้ แล้วจะกลายเป็นกรองแล้วไม่กรอง

   ── ทำไมเป็น "เมธอด" ไม่ใช่ getter ────────────────────────────────────────
   คอมโพเนนต์ที่ใช้ตัวนี้เขียนว่า `{ ...staffPicker(groups), ... }` ซึ่ง spread
   **คัดลอกค่าที่ getter คืนในวินาทีนั้น** ไม่ใช่ตัว getter เอง — ผลคือรายการถูกคำนวณ
   ครั้งเดียวตอนสร้างคอมโพเนนต์แล้วค้างอยู่อย่างนั้น กรองยังไงก็ไม่ขยับ
   (เจอจริง 2026-10-02 ตอนแยกไฟล์นี้ออกมาใช้ร่วมกัน) · เมธอดรอดจากการ spread
   และ Alpine ก็ติดตามค่าที่อ่านระหว่างเรียกให้อยู่แล้ว เรียกในเทมเพลตเป็น visibleGroups() */

function staffPicker(groups) {
  return {
    staffGroups: groups || [],
    dept: '',

    /** id ที่ต้องซ่อน — คอมโพเนนต์ที่ใช้เขียนทับเมธอดนี้เพื่อบอกเงื่อนไขของตัวเอง */
    hidden() { return []; },

    visibleGroups() {
      const hide = new Set(this.hidden().map(String));
      return this.staffGroups
        .filter(g => !this.dept || String(g.id) === this.dept)
        .map(g => ({ ...g, staff: g.staff.filter(s => !hide.has(String(s.id))) }))
        .filter(g => g.staff.length > 0);
    },

    visibleCount() {
      return this.visibleGroups().reduce((n, g) => n + g.staff.length, 0);
    },

    hiddenCount() {
      return this.hidden().length;
    },

    /** ใส่ค่าที่เลือกไว้ "หลัง" ตัวเลือกถูกเรนเดอร์แล้ว
     *
     *  ตัวเลือกมาจาก x-for ซึ่งเรนเดอร์ในจังหวะเดียวกับที่เราใส่ค่า — ถ้าใส่ก่อน
     *  <option> เกิด ช่อง select จะค้างที่ "— เลือก —" ทั้งที่ข้อมูลมีคนอยู่
     *  แล้วพอกดบันทึก ค่าที่ถูกส่งไปคือค่าของ select (ว่าง) ไม่ใช่ค่าในข้อมูล
     *  → เซิร์ฟเวอร์ตีกลับว่า "ต้องเลือกพนักงาน" ทั้งที่หน้าจอดูเหมือนกรอกครบ
     *  (เจอจริง 2026-10-02 ตอนกดแก้ไขรายการวันลา)
     *
     *  แปลงเป็น string ด้วย เพราะ <option> ใช้ค่า string — เลขดิบจะไม่ match
     */
    applySelection(value, set) {
      this.$nextTick(() => set(value ? String(value) : ''));
    },

    /** เรียกเมื่อเงื่อนไขเปลี่ยน (ฝ่าย/วันที่/จุดงาน) — ล้างคนที่หลุดจากลิสต์
     *
     *  ขาดข้อนี้ไม่ได้: หน้าจอจะโชว์ "— เลือก —" แต่ค่าเดิมยังติดไปกับฟอร์ม
     *  แล้วบันทึกคนผิดโดยไม่มีใครรู้
     */
    pruneSelection(current, clear) {
      if (!current) return;
      const ids = this.visibleGroups().flatMap(g => g.staff.map(s => String(s.id)));
      if (!ids.includes(String(current))) clear();
    },
  };
}

/** ช่วงวันสองช่วงคาบกันไหม — เทียบ ISO เป็นข้อความได้ตรงๆ (YYYY-MM-DD เรียงตามวันอยู่แล้ว) */
function overlapsIso(aFrom, aTo, bFrom, bTo) {
  return aFrom <= (bTo || bFrom) && (aTo || aFrom) >= bFrom;
}
